// ============================================================
// MiniMind — research/GenerationRuntime.ts
// ============================================================
// Phase 67: Main-thread generation runtime bridge.
//
// Architecture:
//
//   GenerationWorkspace (UI)
//        │
//   GenerationRuntime
//        │
//   GenerationWorker (Web Worker)
//        │
//   GenerationEvaluator (real generation)
//
// Responsibilities:
//   - load checkpoint
//   - restore model (in worker)
//   - generate text (in worker)
//   - evaluate generation
//   - return structured result
//
// Design:
//   - Web Worker for generation (doesn't freeze browser)
//   - Reuses existing GenerationEvaluator
//   - Reuses existing checkpoint loading
//   - No React/UI logic
//   - Follows TrainingRuntime pattern
//
// Usage:
//   const runtime = new GenerationRuntime();
//   const result = await runtime.generate({
//     sessionId: "rs-xxx",
//     checkpointJSON: "...",
//     prompt: "Once upon a time",
//     ...
//   });
// ============================================================

