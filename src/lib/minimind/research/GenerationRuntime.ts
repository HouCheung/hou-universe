// ============================================================
// Runtime Types
// ============================================================

export type GenerationRuntimeStatus =
  | "idle"
  | "generating"
  | "completed"
  | "stopped"
  | "error"
  | "cancelled";

export interface GenerationRuntimeState {
  requestId: string;
  status: GenerationRuntimeStatus;
  progress: { tokensGenerated: number; maxTokens: number; elapsedMs: number } | null;
  /** Accumulated generated text so far (Phase 71 streaming) */
  textSoFar: string;
  result: GenerationResult | null;
  error: string | null;
  /** Settle the pending generate() promise (assigned inside its executor). */
  resolve?: (result: GenerationResult) => void;
  reject?: (error: Error) => void;
}

export interface GenerateOptions {
  /** Session/experiment ID */
  sessionId: string;
  /** Experiment ID — resolved from session automatically, or set explicitly for provenance */
  experimentId?: string;
  /** Run ID (if applicable) */
  runId?: string;
  /** Checkpoint ID (for trained model generation) */
  checkpointId?: string;
  /** Serialized checkpoint data */
  checkpointJSON?: string;
  /** The prompt text */
  prompt: string;
  /** Generation parameters */
  params?: GenerationEvalOptions;
  /** Model configuration */
  modelConfig?: Partial<GenerationModelConfig>;
  /** Tokenizer training corpus */
  corpus?: string[];
  /** Whether this is a baseline generation */
  isBaseline?: boolean;
  /** Abort signal for cancellation */
  signal?: AbortSignal;
  /** Callback for progress updates */
  onProgress?: (progress: { tokensGenerated: number; maxTokens: number; elapsedMs: number }) => void;
  /**
   * REAL token streaming callback (Phase 71).
   * Fires for every token generated by the model.
   * Called with the decoded token string, its index, and accumulated text so far.
   */
  onToken?: (token: string, tokenIndex: number, textSoFar: string) => void;
}

// ============================================================
// GenerationRuntime
// ============================================================

/** Phase 72: Maximum time a generation can run before being considered stuck */
const GENERATION_TIMEOUT_MS = 120_000; // 2 minutes

export class GenerationRuntime {
  private activeWorkers: Map<string, Worker>;
  private activeStates: Map<string, GenerationRuntimeState>;
  private activeTimeouts: Map<string, ReturnType<typeof setTimeout>>;

  constructor() {
    this.activeWorkers = new Map();
    this.activeStates = new Map();
    this.activeTimeouts = new Map();
  }

  /**
   * Generate text from a trained checkpoint or baseline model.
   *
   * This is the primary API for generation. It:
   * 1. Validates inputs
   * 2. Spawns a Web Worker
   * 3. Runs real generation in the worker
   * 4. Returns structured GenerationResult
   *
   * @param options - Generation options
   * @returns Promise resolving to GenerationResult
   */
  async generate(options: GenerateOptions): Promise<GenerationResult> {
    const requestId = generateRequestId();

    // Validate
    if (!options.prompt || options.prompt.trim().length === 0) {
      throw new Error("GenerationRuntime: prompt cannot be empty");
    }

    // Resolve experiment/run identity from options or session for provenance tracking.
    const session = workspace.getSession(options.sessionId);
    const runId = options.runId ?? session?.runId;
    const experimentId = options.experimentId ?? session?.experimentId;

    if (!options.isBaseline && !options.checkpointJSON) {
      // Try to get checkpoint from session (Phase 85: load the full blob from
      // the CheckpointStore via the active checkpoint id).
      const activeCheckpoint = session?.activeCheckpoint;
      if (activeCheckpoint?.checkpointDataPersisted && activeCheckpoint.id) {
        const stored = await checkpointStore.get(activeCheckpoint.id);
        if (!stored) {
          throw new Error(
            "GenerationRuntime: checkpoint data is missing from the store for trained generation. " +
            "Pass checkpointJSON or set isBaseline: true."
          );
        }
        options.checkpointJSON = stored;
        options.checkpointId = activeCheckpoint.id;
      } else if (!options.isBaseline) {
        throw new Error(
          "GenerationRuntime: no checkpoint data provided for trained generation. " +
          "Pass checkpointJSON or set isBaseline: true."
        );
      }
    }

    // Build model config (Phase 80 — production config is the single source
    // of truth; the worker reconstructs from checkpoint metadata when present).
    const production = getProductionModelConfig();
    const modelConfig: GenerationModelConfig = {
      vocabSize: options.modelConfig?.vocabSize ?? production.vocabSize,
      dModel: options.modelConfig?.dModel ?? production.dModel,
      numHeads: options.modelConfig?.numHeads ?? production.numHeads,
      dFF: options.modelConfig?.dFF ?? production.dFF,
      numLayers: options.modelConfig?.numLayers ?? production.numLayers,
      maxSeqLen: options.modelConfig?.maxSeqLen ?? production.maxSeqLen,
    };

    // Build corpus (Phase 80 — resolve from the session's dataset so
    // generation tokenizes with the same foundation corpus as training).
    const corpus = options.corpus ?? resolveTrainingDataset(session?.dataset).corpus;

    // Build generation params
    const generationParams = {
      prompt: options.prompt,
      maxTokens: options.params?.maxTokens ?? 30,
      temperature: options.params?.temperature ?? 0.8,
      topK: options.params?.topK ?? 40,
      topP: options.params?.topP ?? 0.9,
      seed: options.params?.seed ?? 42,
      eosTokenId: options.params?.eosTokenId ?? 3,
    };

    // Initialize state
    const state: GenerationRuntimeState = {
      requestId,
      status: "generating",
      progress: null,
      textSoFar: "",
      result: null,
      error: null,
    };
    this.activeStates.set(requestId, state);

    // Spawn worker
    const worker = this.spawnWorker(
      requestId,
      options.sessionId,
      experimentId,
      options.checkpointId,
      options.checkpointJSON,
      modelConfig,
      generationParams,
      corpus,
      options.isBaseline ?? false,
      options.signal
    );
    this.activeWorkers.set(requestId, worker);

    // Set up abort signal listener
    if (options.signal) {
      options.signal.addEventListener("abort", () => {
        this.cancel(requestId);
      }, { once: true });

      // If the signal is already aborted, cancel immediately
      if (options.signal.aborted) {
        this.cancel(requestId);
      }
    }

    // Phase 72: Set up generation timeout — prevents UI from being
    // permanently stuck in "Generating..." if the worker hangs
    const timeoutId = setTimeout(() => {
      if (this.activeStates.has(requestId) &&
          this.activeStates.get(requestId)?.status === "generating") {
        const state = this.activeStates.get(requestId)!;
        state.status = "error";
        state.error = "Generation timed out — the model took too long to respond";
        // Reject the pending promise (worker.terminate() does not fire onerror)
        state.reject?.(new Error(state.error));
        this.cleanup(requestId);
      }
    }, GENERATION_TIMEOUT_MS);
    this.activeTimeouts.set(requestId, timeoutId);

    // Wait for result
    return new Promise<GenerationResult>((resolve, reject) => {
      state.resolve = resolve;
      state.reject = reject;

      worker.onmessage = (e: MessageEvent<GenerationWorkerEvent>) => {
        const event = e.data;

        switch (event.type) {
          case "started": {
            break;
          }

          case "token": {
            // Phase 71: Real token streaming
            state.textSoFar = event.textSoFar;
            state.progress = {
              tokensGenerated: event.tokenIndex + 1,
              maxTokens: generationParams.maxTokens,
              elapsedMs: 0, // worker doesn't track per-token elapsed
            };
            options.onToken?.(event.token, event.tokenIndex, event.textSoFar);
            break;
          }

          case "progress": {
            state.progress = {
              tokensGenerated: event.tokensGenerated,
              maxTokens: event.maxTokens,
              elapsedMs: event.elapsedMs,
            };
            options.onProgress?.(state.progress);
            break;
          }

          case "completed": {
            state.status = "completed";
            // Ensure identity fields are on the result for provenance
            const result = {
              ...event.result,
              experimentId: event.result.experimentId ?? experimentId,
              runId: event.result.runId ?? runId,
            };
            state.result = result;
            state.textSoFar = result.generatedText;
            this.cleanup(requestId);

            // Save to history
            this.saveToHistory(result);

            resolve(result);
            break;
          }

          case "stopped": {
            // Phase 71: Generation was stopped by user
            state.status = "stopped";
            const result = {
              ...event.result,
              experimentId: event.result.experimentId ?? experimentId,
              runId: event.result.runId ?? runId,
              status: "stopped" as const,
            };
            state.result = result;
            state.textSoFar = result.generatedText;
            this.cleanup(requestId);

            // Save partial result to history
            this.saveToHistory(result);

            resolve(result);
            break;
          }

          case "error": {
            state.status = "error";
            state.error = event.error;
            this.cleanup(requestId);
            reject(new Error(event.error));
            break;
          }

          case "cancelled": {
            state.status = "cancelled";
            this.cleanup(requestId);
            resolve({
              requestId,
              sessionId: options.sessionId,
              experimentId,
              runId,
              checkpointId: options.checkpointId,
              status: "cancelled",
              prompt: options.prompt,
              generatedText: "",
              generatedIds: [],
              metrics: {
                tokenCount: 0,
                avgLogProb: 0,
                perplexity: Infinity,
                stopReason: "error",
                durationMs: 0,
              },
              generationConfig: {
                prompt: options.prompt,
                params: generationParams,
              },
              isBaseline: options.isBaseline ?? false,
              timestamp: Date.now(),
            });
            break;
          }
        }
      };

      worker.onerror = (err: ErrorEvent) => {
        const errorMsg = err.message || "Unknown worker error";
        state.status = "error";
        state.error = errorMsg;
        this.cleanup(requestId);
        reject(new Error(`GenerationWorker error: ${errorMsg}`));
      };
    });
  }

  /**
   * Generate both baseline and trained results, then compare them.
   *
   * This runs baseline generation first (without checkpoint),
   * then trained generation (with checkpoint), and returns
   * a structured comparison.
   *
   * @param options - Generation options (must include checkpointJSON for trained)
   * @returns Promise resolving to GenerationComparisonResult
   */
  async compare(options: GenerateOptions): Promise<GenerationComparisonResult> {
    const comparisonId = generateComparisonId();

    // Generate baseline (no checkpoint)
    const baseline = await this.generate({
      ...options,
      isBaseline: true,
      checkpointJSON: undefined,
      checkpointId: undefined,
    });

    // Generate trained (with checkpoint)
    const trained = await this.generate({
      ...options,
      isBaseline: false,
    });

    return createComparison(
      comparisonId,
      options.sessionId,
      baseline,
      trained
    );
  }

  /**
   * Cancel an active generation (Phase 74).
   *
   * Terminates the worker immediately — the synchronous generation loop
   * cannot process a cooperative cancel message mid-token — and rejects
   * the pending promise with an AbortError so callers can stop cleanly.
   *
   * @param requestId - The request ID to cancel
   */
  cancel(requestId: string): void {
    const worker = this.activeWorkers.get(requestId);
    if (!worker) return;

    const state = this.activeStates.get(requestId);

    worker.terminate();

    const abortError = new Error("Generation cancelled by user");
    abortError.name = "AbortError";
    state?.reject?.(abortError);

    this.cleanup(requestId);
  }

  /**
   * Get the current state of a generation request.
   */
  getState(requestId: string): GenerationRuntimeState | null {
    return this.activeStates.get(requestId) ?? null;
  }

  /**
   * Save a generation result to history.
   */
  private saveToHistory(result: GenerationResult): void {
    try {
      generationHistory.save({
        requestId: result.requestId,
        sessionId: result.sessionId,
        experimentId: result.experimentId,
        runId: result.runId,
        checkpointId: result.checkpointId,
        prompt: result.prompt,
        generatedText: result.generatedText,
        fullGeneratedText: result.generatedText,
        metrics: {
          tokenCount: result.metrics.tokenCount,
          avgLogProb: result.metrics.avgLogProb,
          perplexity: result.metrics.perplexity,
          stopReason: result.metrics.stopReason,
          durationMs: result.metrics.durationMs,
        },
        generationConfig: {
          maxTokens: result.generationConfig.params.maxTokens ?? 30,
          temperature: result.generationConfig.params.temperature ?? 0.8,
          topK: result.generationConfig.params.topK ?? 40,
          topP: result.generationConfig.params.topP ?? 0.9,
          seed: result.generationConfig.params.seed,
        },
        isBaseline: result.isBaseline,
        timestamp: result.timestamp,
      });
    } catch {
      // History save is best-effort — don't fail generation
    }
  }

  /**
   * Clean up worker, state, and timeout for a request.
   */
  private cleanup(requestId: string): void {
    const worker = this.activeWorkers.get(requestId);
    if (worker) {
      worker.terminate();
      this.activeWorkers.delete(requestId);
    }
    const timeout = this.activeTimeouts.get(requestId);
    if (timeout) {
      clearTimeout(timeout);
      this.activeTimeouts.delete(requestId);
    }
    this.activeStates.delete(requestId);
  }

  /**
   * Spawn a Web Worker for generation.
   */
  private spawnWorker(
    requestId: string,
    sessionId: string,
    experimentId: string | undefined,
    checkpointId: string | undefined,
    checkpointJSON: string | undefined,
    modelConfig: GenerationModelConfig,
    generationParams: {
      prompt: string;
      maxTokens: number;
      temperature: number;
      topK: number;
      topP: number;
      seed?: number;
      eosTokenId: number;
    },
    corpus: string[],
    isBaseline: boolean,
    signal?: AbortSignal
  ): Worker {
    const worker = new Worker(
      new URL("./worker/GenerationWorker.ts", import.meta.url)
    );

    // Set up abort signal forwarding
    if (signal) {
      signal.addEventListener("abort", () => {
        worker.postMessage({ type: "cancel", requestId });
      }, { once: true });
    }

    // Send start command
    worker.postMessage({
      type: "start",
      requestId,
      sessionId,
      experimentId,
      checkpointId,
      checkpointJSON,
      modelConfig,
      generationParams,
      corpus,
      isBaseline,
    });

    return worker;
  }
}

